#!/usr/bin/env bash
# `instrument.sh` — the pre-registered instrument checks (PREREGISTRATION.md,
# "Instrument checks"), run through the real path: suites built by
# make-suite.mjs, episodes played by `gauntlet run`, bundles verified and
# scored by analyze.mjs.
#
#   I1  skill:0.25 vs skill:0.75 per game  → must be SEPARATED (rhae-v1)
#   I2  skill:0.25 vs skill:0.25           → must be NOT_SEPARATED (all cells D=0)
#   I2s label-swap symmetry: analyze(A,B) = −analyze(B,A) exactly
#
# The skill dial's expert is game-specific (`skill:<p>:baseline:<game>:engine`),
# so each arm runs per game and the per-game bundles are merged into one
# composite bundle per arm. Every trajectory in every merged bundle is
# replay-verified again by analyze.mjs.
#
# Usage: ./instrument.sh   (from gauntlet/studies/separation-pilot)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
g="$(cd "$here/../.." && pwd)"            # the gauntlet package root
cd "$here"                                 # every relative path below is study-relative
out="$here/outputs/instrument"
mkdir -p "$out"
rm -rf "$out/bundles"
mkdir -p "$out/bundles"


# 1. Split the committed smallest suite into per-game subsets (derived, but
#    regenerated byte-identically from the committed suite every run).
node -e '
const fs = require("fs");
const suite = JSON.parse(fs.readFileSync("outputs/suites/suite.smallest-8.json", "utf8"));
fs.mkdirSync("outputs/suites/instrument", { recursive: true });
for (const g of suite.games) {
  const sub = { ...suite, id: `${suite.id}-instrument-${g.id}`, games: [g] };
  fs.writeFileSync(`outputs/suites/instrument/${g.id}.json`, JSON.stringify(sub, null, 2) + "\n");
}
console.log("per-game suites:", suite.games.map((g) => g.id).join(", "));
'

# 2. Play every arm. Six dial runs (3 games × 2 dials) + I2 reuses the 0.25
#    arms (same spec, same seeds ⇒ byte-identical trajectories, so the I2 pair
#    is two INDEPENDENT invocations: the 0.25 run and a second fresh 0.25 run).
#    The arm list is DERIVED from the committed smallest suite — a re-cut that
#    changes the suite's games automatically changes the instruments with it.
games=()
while IFS= read -r g_; do games+=("$g_"); done < <(node -e '
  const s = JSON.parse(require("fs").readFileSync("outputs/suites/suite.smallest-8.json", "utf8"));
  for (const g of s.games) console.log(g.id);
')
echo "instrument games (from suite.smallest-8.json): ${games[*]}"
declare -A runs
for g_ in "${games[@]}"; do
  runs[$g_]="$(node -e '
    const s = JSON.parse(require("fs").readFileSync(`outputs/suites/instrument/${process.argv[1]}.json`, "utf8"));
    console.log(s.games.reduce((a, g) => a + g.tiers.reduce((x, t) => x + t.seeds.length, 0), 0));
  ' "$g_")"
done
episodes_desc=""
for g_ in "${games[@]}"; do episodes_desc+=" ${runs[$g_]} $g_,"; done
echo "episodes per arm:${episodes_desc%,}"

for p in 0.25 0.75; do
  for g_ in "${games[@]}"; do
    echo "=== arm skill:$p:$g_ (${runs[$g_]} episodes) ==="
    node "$g/cli/gauntlet.js" run \
      --suite "outputs/suites/instrument/$g_.json" \
      --agent "skill:$p:baseline:$g_:engine" \
      --out "$out/bundles/i1-$g_-p$p"
  done
done
# I2's second independent 0.25 invocation (fresh streams, same seeds+spec).
for g_ in "${games[@]}"; do
  echo "=== arm skill:0.25 again:$g_ ==="
  node "$g/cli/gauntlet.js" run \
    --suite "outputs/suites/instrument/$g_.json" \
    --agent "skill:0.25:baseline:$g_:engine" \
    --out "$out/bundles/i2-$g_-p0.25"
done

# 3. Merge per-game bundles into composite arm bundles: copy each per-game
#    bundle's game directory (trajectories live under <game>/<tier>/) into the
#    composite root, and attach the committed smallest-suite manifest so the
#    composite is self-describing. No run.json at the root: analyze.mjs falls
#    back to the trajectories' own agent ids for labels.
for arm in i1-p0.25 i1-p0.75 i2-p0.25a i2-p0.25b; do
  rm -rf "$out/$arm"          # never merge into a stale composite: nested game dirs duplicate trajectories
  mkdir -p "$out/$arm"
  cp outputs/suites/suite.smallest-8.json "$out/$arm/suite.json"
done
for g_ in "${games[@]}"; do
  cp -r "$out/bundles/i1-$g_-p0.25/$g_" "$out/i1-p0.25/$g_"
  cp -r "$out/bundles/i1-$g_-p0.75/$g_" "$out/i1-p0.75/$g_"
  cp -r "$out/bundles/i1-$g_-p0.25/$g_" "$out/i2-p0.25a/$g_"
  cp -r "$out/bundles/i2-$g_-p0.25/$g_" "$out/i2-p0.25b/$g_"
done

# 4. Analyze: I1 (must separate), I2 (must not), and the label-swap symmetry.
node analyze.mjs "$out/i1-p0.25" "$out/i1-p0.75" --json > "$out/I1.json"
node analyze.mjs "$out/i2-p0.25a" "$out/i2-p0.25b" --json > "$out/I2.json"
node analyze.mjs "$out/i1-p0.75" "$out/i1-p0.25" --json > "$out/I1-swapped.json"

node -e '
const fs = require("fs");
const i1 = JSON.parse(fs.readFileSync("outputs/instrument/I1.json", "utf8"));
const i2 = JSON.parse(fs.readFileSync("outputs/instrument/I2.json", "utf8"));
const sw = JSON.parse(fs.readFileSync("outputs/instrument/I1-swapped.json", "utf8"));
const rhae = (a) => a.comparisons.find((c) => c.profile === "rhae-v1").readings.raw;
const i1r = rhae(i1), i2r = rhae(i2), swr = rhae(sw);
let ok = true;
const expect = (cond, msg) => { console.log((cond ? "PASS" : "FAIL") + " " + msg); if (!cond) ok = false; };
expect(i1r.verdict === "SEPARATED" && i1r.D > 0, `I1 separates with D>0 (D=${i1r.D}, ci=[${i1r.ci95}], sign ${i1r.signAgree})`);
expect(i2r.verdict === "NOT_SEPARATED" && i2r.D === 0, `I2 does not separate, D=0 exactly (verdict ${i2r.verdict}, D=${i2r.D})`);
expect(i1r.D === -swr.D && i1r.ci95[0] === -swr.ci95[1] && i1r.ci95[1] === -swr.ci95[0], "label swap negates D and the interval bounds exactly");
for (const p of ["squared-outcome", "chance-adjusted"]) {
  const c = i1.comparisons.find((x) => x.profile === p).readings.raw;
  console.log(`note I1 [${p}]: ${c.verdict} D=${c.D} ci=[${c.ci95}]`);
}
console.log(ok ? "INSTRUMENT-CHECKS: PASS" : "INSTRUMENT-CHECKS: FAIL");
process.exit(ok ? 0 : 1);
'
