#!/usr/bin/env sh
# Reproduce the tier-audit tables from a clean checkout. The raw episode
# trajectories are not committed (they re-derive deterministically); this
# script re-derives any missing or stale cell with run-cells.mjs — a cell
# counts as present only when every planned seed has a trajectory that
# records the registry's current game version — then replay-verifies every
# bundle, recomputes tiers.json, and proves it is byte-identical to the
# committed one.
#
#   ./reproduce.sh          # from gauntlet/studies/tier-audit
#
# Engine games need stockfish and gnugo installed (Debian: apt-get install
# stockfish gnugo); #107 recorded Stockfish 17.1 and GNU Go 3.8.
set -eu
cd "$(dirname "$0")"

echo "reproduce: re-deriving missing or stale cells (this is the long step)"
node run-cells.mjs

echo "reproduce: replay-verifying every bundle"
node verify-cells.mjs

echo "reproduce: recomputing tiers.json"
cp tiers.json tiers.json.expected
node compute-tiers.mjs
if ! diff -q tiers.json tiers.json.expected > /dev/null; then
  echo "reproduce: regenerated tiers.json differs from the committed one" >&2
  exit 1
fi
rm tiers.json.expected
echo "reproduce: tiers.json regenerated byte-identical"
echo "reproduce: REPRO_EXIT=0"
