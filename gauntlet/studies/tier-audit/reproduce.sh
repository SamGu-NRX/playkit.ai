#!/usr/bin/env sh
# Regenerate the tier-audit tables from the committed cell bundles plus the
# committed skill-dial reuse, and prove the committed tiers.json is
# byte-identical to the regeneration.
set -eu
cd "$(dirname "$0")"

node verify-cells.mjs

cp tiers.json tiers.json.expected
node compute-tiers.mjs
if ! diff -q tiers.json tiers.json.expected > /dev/null; then
  echo "reproduce: regenerated tiers.json differs from the committed one" >&2
  exit 1
fi
rm tiers.json.expected
echo "reproduce: tiers.json regenerated byte-identical"
